#!/usr/bin/env python3
"""names_snapshot.py : record the live project's shared annotations.
  annotations/names.txt      every non-default function name ("addr name", sorted)
  annotations/functions.txt  every function's exact body ("entry start-end[,start-end...]"), so
                             bootstrap reproduces identical boundaries (ghidra_scripts/ApplyFunctions.java)
Commit both. Refuses to shrink names.txt by >10% (wrong project?)."""
import gh
import hcfg

items, off = [], 0
while True:
    d = gh.get("function_bodies", offset=off, limit=1000)
    items += d["items"]
    if not d["has_more"]:
        break
    off += 1000
names = sorted((f["address"], f["name"]) for f in items
               if not f["name"].startswith(("FUN_", "thunk_FUN_", "tmp_")))
p = hcfg.ANNOT / "names.txt"
old = len(p.read_text().splitlines()) if p.exists() else 0
if len(names) < old * 0.9:
    raise SystemExit("refusing: %d names vs %d in %s (wrong project?)" % (len(names), old, p))
p.write_text("".join("%s %s\n" % x for x in names))
fb = sorted((f["address"], ",".join("%s-%s" % (a, b) for a, b in f["ranges"])) for f in items)
(hcfg.ANNOT / "functions.txt").write_text(
    "# entry body-ranges (generated by tools/names_snapshot.py; applied by ApplyFunctions.java)\n"
    + "".join("%s %s\n" % x for x in fb))
print("%d names, %d function bodies -> %s" % (len(names), len(fb), hcfg.ANNOT))
